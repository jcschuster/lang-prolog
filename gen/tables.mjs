// Writes spec/prolog/{ops,builtins}.json and SOURCE from the `swipl` on PATH (the
// devshell's, pinned by flake.lock), checks the hand-curated spec/prolog/control.json
// against them, and writes the tables the tokenizer and completion use to
// packages/codemirror-lang-swipl/src/tables.ts.
import {execFileSync} from "node:child_process"
import {readFileSync, writeFileSync} from "node:fs"

const root = new URL("..", import.meta.url)
const spec = new URL("spec/prolog/", root)

// `-f none`: no user init file; `--no-packs`: no add-ons. Names are printed as code
// lists, which are valid JSON, so no Prolog quoting has to be parsed here.
function swipl(goal) {
  return execFileSync("swipl", ["-f", "none", "--no-packs", "-q", "-g", goal, "-t", "halt"], {encoding: "utf8"})
}

const text = codes => String.fromCodePoint(...codes)
const compare = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

const ops = swipl(`forall(current_op(P, T, N), (atom_codes(N, C), format("~w ~w ~w~n", [P, T, C])))`)
  .trim().split("\n").map(line => {
    const [priority, type, codes] = line.split(" ")
    return {name: text(JSON.parse(codes)), type, priority: Number(priority)}
  })
  .sort((a, b) => compare(a.name, b.name) || compare(a.type, b.type))

// Names starting with `$` are SWI-Prolog's internal predicates.
const builtins = swipl(`forall((predicate_property(system:H, built_in), functor(H, N, A), \\+ sub_atom(N, 0, _, _, '$')),
    (atom_codes(N, C), (predicate_property(system:H, iso) -> I = true ; I = false), format("~w ~w ~w~n", [A, I, C])))`)
  .trim().split("\n").map(line => {
    const [arity, iso, codes] = line.split(" ")
    return {name: text(JSON.parse(codes)), arity: Number(arity), iso: iso == "true"}
  })
  .sort((a, b) => compare(a.name, b.name) || a.arity - b.arity)

const has = name => ops.some(op => op.name == name)
for (const name of [":-", "-->", "is", ","]) if (!has(name)) throw new Error(`ops.json lacks ${name}`)
if (ops.length < 50) throw new Error(`ops.json has only ${ops.length} entries`)
if (builtins.length < 500) throw new Error(`builtins.json has only ${builtins.length} entries`)

const control = JSON.parse(readFileSync(new URL("control.json", spec), "utf8"))
const known = new Set([...ops.map(op => op.name), ...builtins.map(b => b.name)])
const unknown = [...control.control, ...control.directives].filter(name => !known.has(name))
if (unknown.length) throw new Error(`control.json names neither a built-in nor an operator: ${unknown.join(" ")}`)

const version = execFileSync("swipl", ["--version"], {encoding: "utf8"}).trim().replace(/ for \S+$/, "")
const {locked} = JSON.parse(readFileSync(new URL("flake.lock", root), "utf8")).nodes.nixpkgs
const date = new Date(locked.lastModified * 1000).toISOString().slice(0, 10)

const lines = items => `[\n${items.map(item => "  " + JSON.stringify(item)).join(",\n")}\n]\n`
writeFileSync(new URL("ops.json", spec), lines(ops))
writeFileSync(new URL("builtins.json", spec), lines(builtins))
writeFileSync(new URL("SOURCE", spec), `ops.json and builtins.json are read from a fresh swipl by gen/tables.mjs.

swipl: ${version}
nixpkgs: https://github.com/NixOS/nixpkgs/tree/${locked.rev}
nixpkgs narHash: ${locked.narHash}
nixpkgs date: ${date}
`)

const alphanumeric = /^\p{Ll}[\p{ID_Continue}]*$/u
const names = list => JSON.stringify([...new Set(list)])
writeFileSync(new URL("packages/codemirror-lang-swipl/src/tables.ts", root),
  `// Generated by gen/tables.mjs from spec/prolog/*.json (${version}). Do not edit.

export const operators = ${names(ops.map(op => op.name).filter(name => alphanumeric.test(name)))}

export const control = ${names(control.control)}

export const directives = ${names(control.directives)}

export const builtins: [string, number][] = ${JSON.stringify(builtins.map(({name, arity}) => [name, arity]))}
`)
